-- Пользовательские роли больше не используют настраиваемую область данных.
-- Их доступ определяется только набором разрешений, поэтому все существующие
-- пользовательские роли переводятся в глобальную область. Системные роли
-- руководителей сохраняют собственные внутренние ограничения по оргструктуре.
UPDATE roles
SET scope_type = 'global'
WHERE is_system = 0
  AND scope_type <> 'global';
